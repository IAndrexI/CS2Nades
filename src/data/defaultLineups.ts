function defaultPitchForThrow(throwType: ThrowType): number {
  switch (throwType) {
    case 'jumpthrow':
    case 'w_jumpthrow':
    case 'run_jumpthrow':
    case 'crouch_jumpthrow':
      return -35.5
    case 'runthrow':
    case 'walkthrow':
      return -22.0
    default:
      return -28.0
  }
}

function defaultClickForThrow(throwType: ThrowType): MouseClickType {
  if (throwType === 'rightclick') return 'right'
  if (throwType === 'left_right_click' || throwType === 'middleclick') return 'both'
  return 'left'
}

function buildLineup(seed: LineupSeed): Lineup {
  const defaultZ =
    seed.radarFloor === 'lower'
      ? seed.mapId === 'nuke'
        ? -760
        : seed.mapId === 'vertigo'
          ? 11488
          : (DEFAULT_MAP_Z[seed.mapId] ?? 0)
      : (DEFAULT_MAP_Z[seed.mapId] ?? 0)

  const z = seed.z ?? defaultZ
  const pitch = Number((seed.pitch ?? defaultPitchForThrow(seed.throwType)).toFixed(1))
  const world = radarToWorldCoords(seed.mapId, seed.originCoords, z)
  const cal = getMapCalibration(seed.mapId)
  const dx = ((seed.landingCoords.x - seed.originCoords.x) / 100) * 1024 * cal.scale
  const dy = ((seed.originCoords.y - seed.landingCoords.y) / 100) * 1024 * cal.scale
  const yaw = Number(((Math.atan2(dy, dx) * 180) / Math.PI).toFixed(1))

  const distPct = Math.hypot(
    seed.landingCoords.x - seed.originCoords.x,
    seed.landingCoords.y - seed.originCoords.y
  )
  const airTimeSeconds =
    seed.airTimeSeconds ??
    Number(Math.max(1.2, Math.min(5.6, distPct / 11 + 0.9)).toFixed(1))

  const clickType = seed.clickType ?? defaultClickForThrow(seed.throwType)

  return {
    id: seed.id,
    title: seed.title,
    mapId: seed.mapId,
    grenadeType: seed.grenadeType,
    side: seed.side,
    throwType: seed.throwType,
    movementType: seed.movementType,
    movementDetails: seed.movementDetails,
    clickType,
    tickrate: 'cs2_subtick',
    originCoords: seed.originCoords,
    landingCoords: seed.landingCoords,
    ...(seed.radarFloor ? { radarFloor: seed.radarFloor } : {}),
    startLocation: seed.startLocation,
    endLocation: seed.endLocation,
    site: seed.site,
    playerRole: seed.playerRole ?? 'Support',
    ...(seed.proPlayer ? { proPlayer: seed.proPlayer } : {}),
    ...(seed.proTeam ? { proTeam: seed.proTeam } : {}),
    ...(seed.tournament ? { tournament: seed.tournament } : {}),
    ...(seed.externalId ? { externalId: seed.externalId } : {}),
    ...(seed.viewsCount ? { viewsCount: seed.viewsCount } : {}),
    airTimeSeconds,
    tags: seed.tags,
    imageUrl: DEFAULT_LINEUP_IMAGE,
    standingScreenshot: DEFAULT_LINEUP_IMAGE,
    aimScreenshot: DEFAULT_LINEUP_IMAGE,
    landingScreenshot: DEFAULT_LINEUP_IMAGE,
    instructionSteps: [
      {
        id: `${seed.id}-1`,
        stepNumber: 1,
        phase: 'position',
        title: '1. Stand Spot',
        description: seed.standStep,
        imageUrl: DEFAULT_LINEUP_IMAGE,
        keybindHint:
          seed.movementType === 'crouch' || seed.movementType === 'crouch_walk'
            ? 'Hold CTRL at landmark'
            : seed.startLocation
      },
      {
        id: `${seed.id}-2`,
        stepNumber: 2,
        phase: 'aim',
        title: '2. Aim Alignment',
        description: seed.aimStep,
        imageUrl: DEFAULT_LINEUP_IMAGE,
        crosshairNote: seed.aimNote
      },
      {
        id: `${seed.id}-3`,
        stepNumber: 3,
        phase: 'throw',
        title: '3. Movement & Release',
        description: seed.throwStep,
        imageUrl: DEFAULT_LINEUP_IMAGE,
        keybindHint: seed.movementDetails
      }
    ],
    description: seed.description,
    instructions: [seed.standStep, seed.aimStep, seed.throwStep],
    consoleCommand: `setpos ${world.x} ${world.y} ${world.z}; setang ${pitch} ${yaw} 0`,
    cs2Pos: { x: world.x, y: world.y, z: world.z, pitch, yaw },
    difficulty: seed.difficulty ?? 'easy',
    sourceWebsite: seed.sourceWebsite,
    sourceUrl:
      seed.sourceUrl ?? SOURCE_URL_BUILDERS[seed.sourceWebsite](seed.mapId, seed.id, seed.grenadeType),
    inLibrary: true,
    isTeamShared: true,
    createdAt: seed.createdAt ?? '2026-01-01T00:00:00.000Z'
  }
}

