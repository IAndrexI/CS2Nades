// ── ACTION HANDLERS ─────────────────────────────────────────
function downloadFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

function handleDownloadCfg() {
  downloadFile('practice.cfg', generatedCfgScript.value)
}

function handleDownloadGsi() {
  downloadFile('gamestate_integration_cs2nades.cfg', generatedGsiConfig.value)
}

async function copyToClipboard(text: string, type: 'cfg' | 'docker' | 'setpos' | 'gsi') {
  try {
    await navigator.clipboard.writeText(text)
    if (type === 'cfg') {
      copiedCfg.value = true
      setTimeout(() => (copiedCfg.value = false), 2500)
    } else if (type === 'docker') {
      copiedDocker.value = true
      setTimeout(() => (copiedDocker.value = false), 2500)
    } else if (type === 'setpos') {
      copiedSetpos.value = true
      setTimeout(() => (copiedSetpos.value = false), 2500)
    } else if (type === 'gsi') {
      copiedGsi.value = true
      setTimeout(() => (copiedGsi.value = false), 2500)
    }
  } catch (err) {
    console.error('Failed to copy', err)
  }
}
